// Design token engine: DTCG parsing, alias resolution, multi-platform export.
export type TokenType =
  | "color"
  | "dimension"
  | "fontFamily"
  | "fontWeight"
  | "duration"
  | "number"
  | "shadow";

export interface Token {
  path: string; // e.g. color.primitive.blue.500
  type: TokenType;
  value: string; // raw value or alias "{other.path}"
  description?: string | undefined;
}

export interface ResolvedToken extends Token {
  resolved: string | null;
  aliasOf: string | null;
  error?: string;
}

const ALIAS_RE = /^\{([^}]+)\}$/;

export function isAlias(v: string) {
  return ALIAS_RE.test(v.trim());
}

/** Flatten a W3C DTCG JSON document into tokens. Inherits $type from groups. */
export function parseDTCG(doc: unknown): Token[] {
  const out: Token[] = [];
  const walk = (node: any, path: string[], inherited?: string) => {
    if (!node || typeof node !== "object") return;
    const groupType = node.$type ?? inherited;
    if ("$value" in node) {
      out.push({
        path: path.join("."),
        type: (groupType ?? "number") as TokenType,
        value: typeof node.$value === "string" ? node.$value : JSON.stringify(node.$value),
        description: node.$description,
      });
      return;
    }
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith("$")) continue;
      walk(v, [...path, k], groupType);
    }
  };
  walk(doc, []);
  return out;
}

/** Rebuild a DTCG document from flat tokens. */
export function toDTCG(tokens: Token[]) {
  const root: any = {};
  for (const t of tokens) {
    const parts = t.path.split(".");
    let cur = root;
    parts.slice(0, -1).forEach((p) => (cur = cur[p] ??= {}));
    cur[parts[parts.length - 1]!] = {
      $type: t.type,
      $value: t.value,
      ...(t.description ? { $description: t.description } : {}),
    };
  }
  return root;
}

/** Resolve every alias chain; detects missing references and cycles. */
export function resolveTokens(tokens: Token[]): ResolvedToken[] {
  const map = new Map(tokens.map((t) => [t.path, t]));
  const resolveOne = (t: Token): { value: string | null; error?: string } => {
    const seen = new Set<string>([t.path]);
    let cur = t.value.trim();
    while (isAlias(cur)) {
      const ref = cur.match(ALIAS_RE)![1]!;
      if (seen.has(ref)) return { value: null, error: `Circular reference via ${ref}` };
      const next = map.get(ref);
      if (!next) return { value: null, error: `Unknown token ${ref}` };
      seen.add(ref);
      cur = next.value.trim();
    }
    return { value: cur };
  };
  return tokens.map((t) => {
    const r = resolveOne(t);
    const m = t.value.trim().match(ALIAS_RE);
    return { ...t, resolved: r.value, aliasOf: m ? m[1]! : null, ...(r.error ? { error: r.error } : {}) };
  });
}

export function groupOf(path: string) {
  return path.split(".")[0] ?? path;
}

const kebab = (p: string) => p.replace(/\./g, "-").replace(/[^a-zA-Z0-9-]/g, "-");
const camel = (p: string) =>
  p
    .split(/[.\-_]/)
    .map((s, i) => (i === 0 ? s : s.charAt(0).toUpperCase() + s.slice(1)))
    .join("")
    .replace(/^(\d)/, "_$1");

export type ExportTarget = "css" | "tailwind" | "typescript" | "swift" | "kotlin" | "json";

export const EXPORT_TARGETS: { id: ExportTarget; label: string; file: string }[] = [
  { id: "css", label: "CSS Variables", file: "tokens.css" },
  { id: "tailwind", label: "Tailwind v4", file: "tailwind.theme.css" },
  { id: "typescript", label: "TypeScript", file: "tokens.ts" },
  { id: "swift", label: "iOS Swift", file: "Tokens.swift" },
  { id: "kotlin", label: "Android Kotlin", file: "Tokens.kt" },
  { id: "json", label: "DTCG JSON", file: "tokens.json" },
];

const twPrefix: Record<TokenType, string> = {
  color: "color",
  dimension: "spacing",
  fontFamily: "font",
  fontWeight: "font-weight",
  duration: "duration",
  number: "number",
  shadow: "shadow",
};

function hexToRgba(hex: string) {
  const h = hex.replace("#", "");
  const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h.padEnd(8, "f");
  const [r = 0, g = 0, b = 0, a = 1] = [0, 2, 4, 6].map((i) => parseInt(full.slice(i, i + 2), 16) / 255);
  return { r, g, b, a };
}

export function exportTokens(tokens: Token[], target: ExportTarget): string {
  const resolved = resolveTokens(tokens).filter((t) => t.resolved !== null);
  const header = "Generated by Nexus Design OS — do not edit manually";
  switch (target) {
    case "css":
      return `/* ${header} */\n:root {\n${resolved
        .map((t) => `  --${kebab(t.path)}: ${t.aliasOf ? `var(--${kebab(t.aliasOf)})` : t.value};`)
        .join("\n")}\n}\n`;
    case "tailwind":
      return `/* ${header} */\n@theme {\n${resolved
        .map((t) => `  --${twPrefix[t.type]}-${kebab(t.path.split(".").slice(1).join(".") || t.path)}: ${t.resolved};`)
        .join("\n")}\n}\n`;
    case "typescript":
      return `// ${header}\nexport const tokens = {\n${resolved
        .map((t) => `  ${JSON.stringify(t.path)}: ${JSON.stringify(t.resolved)},`)
        .join("\n")}\n} as const;\n\nexport type TokenName = keyof typeof tokens;\n`;
    case "swift":
      return `// ${header}\nimport SwiftUI\n\npublic enum Tokens {\n${resolved
        .map((t) => {
          if (t.type === "color" && t.resolved!.startsWith("#")) {
            const { r, g, b, a } = hexToRgba(t.resolved!);
            return `  public static let ${camel(t.path)} = Color(red: ${r.toFixed(3)}, green: ${g.toFixed(3)}, blue: ${b.toFixed(3)}, opacity: ${a.toFixed(2)})`;
          }
          const n = parseFloat(t.resolved!);
          return Number.isFinite(n) && t.type !== "fontFamily"
            ? `  public static let ${camel(t.path)}: CGFloat = ${n}`
            : `  public static let ${camel(t.path)} = ${JSON.stringify(t.resolved)}`;
        })
        .join("\n")}\n}\n`;
    case "kotlin":
      return `// ${header}\npackage com.nexus.tokens\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\nobject Tokens {\n${resolved
        .map((t) => {
          if (t.type === "color" && t.resolved!.startsWith("#")) {
            const h = t.resolved!.replace("#", "");
            const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
            const argb = full.length === 8 ? full.slice(6) + full.slice(0, 6) : "FF" + full;
            return `    val ${camel(t.path)} = Color(0x${argb.toUpperCase()})`;
          }
          const n = parseFloat(t.resolved!);
          if (t.type === "dimension" && Number.isFinite(n)) return `    val ${camel(t.path)} = ${n}.dp`;
          return `    val ${camel(t.path)} = ${JSON.stringify(t.resolved)}`;
        })
        .join("\n")}\n}\n`;
    case "json":
      return JSON.stringify(toDTCG(tokens), null, 2);
  }
}

/** Find hardcoded hex colors / px values in source code that should use tokens. */
export function auditCode(code: string, tokens: Token[]) {
  const resolved = resolveTokens(tokens);
  const issues: { line: number; match: string; message: string; suggestion?: string }[] = [];
  code.split("\n").forEach((ln, i) => {
    for (const m of ln.matchAll(/#[0-9a-fA-F]{3,8}\b/g)) {
      const hit = resolved.find((t) => t.type === "color" && t.resolved?.toLowerCase() === m[0].toLowerCase());
      issues.push({ line: i + 1, match: m[0], message: "Hardcoded color", ...(hit ? { suggestion: hit.path } : {}) });
    }
    for (const m of ln.matchAll(/\b\d+px\b/g)) {
      const hit = resolved.find((t) => t.type === "dimension" && t.resolved === m[0]);
      issues.push({ line: i + 1, match: m[0], message: "Hardcoded spacing", ...(hit ? { suggestion: hit.path } : {}) });
    }
  });
  return issues;
}
